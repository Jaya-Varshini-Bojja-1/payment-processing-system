package com.portfolio.paymentsystem.transfer.domain;

import java.time.Instant;
import java.util.UUID;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.springframework.data.domain.Persistable;

import com.portfolio.paymentsystem.common.domain.Currency;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;

/**
 * One internal P2P wallet-to-wallet movement. This row is the
 * transfer-domain record of "what was requested and between whom"; the
 * {@code ledger_entries} rows posted alongside it (same database
 * transaction, see {@code TransferExecutionService}) are the source of
 * truth for the money itself. Never construct one of these outside
 * {@code TransferExecutionService} — doing so without also posting the
 * matching ledger entries would create a transfer record with no money
 * actually having moved.
 * <p>
 * Implements {@link Persistable} because the id is assigned in application
 * code ({@link #initiate}) rather than generated by the database, and this
 * entity has no {@code @Version} column. Without this, Spring Data JPA's
 * default "is this new?" check (id == null) sees a non-null id and calls
 * {@code entityManager.merge()} instead of {@code persist()} on save —
 * merge operates on a <em>separate</em> managed copy, silently discarding
 * any further mutation of (or generated-timestamp read from) this exact
 * object, such as {@link #markCompleted} called later in the same
 * transaction. {@code Account} avoids this only incidentally, because it
 * has a {@code @Version} field that Spring Data checks first.
 */
@Entity
@Table(name = "transfers")
public class Transfer implements Persistable<UUID> {

    @Id
    @Column(nullable = false, updatable = false)
    private UUID id;

    @Transient
    private boolean isNew = true;

    @Column(name = "initiator_user_id", nullable = false, updatable = false)
    private UUID initiatorUserId;

    @Column(name = "source_account_id", nullable = false, updatable = false)
    private UUID sourceAccountId;

    @Column(name = "destination_account_id", nullable = false, updatable = false)
    private UUID destinationAccountId;

    @Column(name = "destination_user_id", nullable = false, updatable = false)
    private UUID destinationUserId;

    @Column(name = "amount_paise", nullable = false, updatable = false)
    private long amountPaise;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 3, updatable = false)
    private Currency currency;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private TransferStatus status;

    @Column(name = "failure_reason", length = 255)
    private String failureReason;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Transfer() {
        // JPA
    }

    public static Transfer initiate(
            UUID initiatorUserId, UUID sourceAccountId, UUID destinationAccountId,
            UUID destinationUserId, long amountPaise, Currency currency) {
        Transfer transfer = new Transfer();
        transfer.id = UUID.randomUUID();
        transfer.initiatorUserId = initiatorUserId;
        transfer.sourceAccountId = sourceAccountId;
        transfer.destinationAccountId = destinationAccountId;
        transfer.destinationUserId = destinationUserId;
        transfer.amountPaise = amountPaise;
        transfer.currency = currency;
        transfer.status = TransferStatus.PENDING;
        return transfer;
    }

    public void markCompleted() {
        this.status = TransferStatus.COMPLETED;
    }

    public void markFailed(String reason) {
        this.status = TransferStatus.FAILED;
        this.failureReason = reason;
    }

    @Override
    public UUID getId() {
        return id;
    }

    @Override
    public boolean isNew() {
        return isNew;
    }

    /**
     * Fired once the INSERT for this exact object actually executes, and
     * also on load of a pre-existing row — from that point on {@code save()}
     * must go through {@code merge()} like any other update.
     */
    @PostPersist
    @PostLoad
    void markNotNew() {
        this.isNew = false;
    }

    public UUID getInitiatorUserId() {
        return initiatorUserId;
    }

    public UUID getSourceAccountId() {
        return sourceAccountId;
    }

    public UUID getDestinationAccountId() {
        return destinationAccountId;
    }

    public UUID getDestinationUserId() {
        return destinationUserId;
    }

    public long getAmountPaise() {
        return amountPaise;
    }

    public Currency getCurrency() {
        return currency;
    }

    public TransferStatus getStatus() {
        return status;
    }

    public String getFailureReason() {
        return failureReason;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
